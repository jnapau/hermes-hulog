import type { CourseCode, Question } from './types';

const TAMA_MALI = [
  { key: 'TAMA', text: 'Tama' },
  { key: 'MALI', text: 'Mali' },
];
const SCAM_LEGIT = [
  { key: 'SCAM', text: 'Scam' },
  { key: 'LEGIT', text: 'Legit' },
];

function tamaMali(
  id: string,
  course: CourseCode,
  prompt: string,
  answer: 'TAMA' | 'MALI',
  answerLabel: string,
  why: string,
  hakbang: string,
): Question {
  return { id, course, format: 'Tama o Mali?', kind: 'binary', prompt, options: TAMA_MALI, answer, answerLabel, why, hakbang };
}

function scamLegit(
  id: string,
  course: CourseCode,
  prompt: string,
  answer: 'SCAM' | 'LEGIT',
  answerLabel: string,
  why: string,
  hakbang: string,
): Question {
  return { id, course, format: 'Scam o Legit?', kind: 'binary', prompt, options: SCAM_LEGIT, answer, answerLabel, why, hakbang };
}

function choice(
  id: string,
  course: CourseCode,
  format: string,
  prompt: string,
  opts: [string, string, string],
  answer: 'A' | 'B' | 'C',
  answerLabel: string,
  why: string,
  hakbang: string,
): Question {
  return {
    id,
    course,
    format,
    kind: 'choice',
    prompt,
    options: opts.map((text, i) => ({ key: 'ABC'[i], text })),
    answer,
    answerLabel,
    why,
    hakbang,
  };
}

